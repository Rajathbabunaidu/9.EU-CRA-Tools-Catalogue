-- nVent EU CRA Hub | Tools Catalogue v1.0
-- ADDITIVE schema; does not modify Template Builder or existing release definitions.
-- Run as Supabase project database owner in a DEVELOPMENT project first.
-- Supabase release definitions are immutable by the EXISTING cra_tm_protect_tool_release trigger.
BEGIN;

CREATE TABLE IF NOT EXISTS public.cra_tm_tool_drafts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tool_id bigint NOT NULL UNIQUE REFERENCES public.cra_tm_tools(id) ON DELETE RESTRICT,
    draft_version text NOT NULL DEFAULT '1.0.0',
    definition jsonb NOT NULL DEFAULT '{"schema_version":1,"sections":[]}'::jsonb,
    revision bigint NOT NULL DEFAULT 1 CHECK (revision > 0),
    is_locked boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT cra_tm_tool_draft_definition_object CHECK (jsonb_typeof(definition) = 'object'),
    CONSTRAINT cra_tm_tool_draft_version_format CHECK (draft_version ~ '^[0-9]+\.[0-9]+\.[0-9]+$')
);

CREATE OR REPLACE FUNCTION public.cra_tm_create_catalogue_tool(
    p_tool_code text, p_tool_name text, p_description text DEFAULT NULL
) RETURNS TABLE (tool_id bigint, draft_id bigint, revision bigint)
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO '' AS $body$
DECLARE v_tool_id bigint; v_draft_id bigint;
BEGIN
    IF p_tool_code IS NULL OR btrim(p_tool_code) !~ '^[A-Za-z][A-Za-z0-9_-]{1,79}$' THEN
       RAISE EXCEPTION 'Tool code must start with a letter and contain 2-80 letters, digits, hyphens or underscores';
    END IF;
    IF nullif(btrim(p_tool_name), '') IS NULL THEN RAISE EXCEPTION 'Tool name is required'; END IF;
    INSERT INTO public.cra_tm_tools(tool_code,tool_name,description,tool_type,is_active)
    VALUES (upper(btrim(p_tool_code)),btrim(p_tool_name),nullif(btrim(p_description),''),'QUESTIONNAIRE',true)
    RETURNING id INTO v_tool_id;
    INSERT INTO public.cra_tm_tool_drafts(tool_id,definition)
    VALUES(v_tool_id, '{"schema_version":1,"sections":[]}'::jsonb)
    RETURNING id INTO v_draft_id;
    RETURN QUERY SELECT v_tool_id,v_draft_id,1::bigint;
END; $body$;

CREATE OR REPLACE FUNCTION public.cra_tm_save_catalogue_tool_draft(
    p_tool_id bigint, p_expected_revision bigint, p_definition jsonb,
    p_draft_version text, p_tool_name text, p_description text DEFAULT NULL
) RETURNS TABLE (draft_id bigint, revision bigint, updated_at timestamptz)
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO '' AS $body$
DECLARE v_id bigint; v_revision bigint; v_updated timestamptz; v_current_version text;
BEGIN
    IF p_expected_revision IS NULL OR p_expected_revision < 1 THEN RAISE EXCEPTION 'Expected draft revision is required'; END IF;
    IF p_definition IS NULL OR jsonb_typeof(p_definition) <> 'object' OR
       p_definition->>'schema_version' <> '1' OR jsonb_typeof(p_definition->'sections') <> 'array' THEN
       RAISE EXCEPTION 'Definition requires schema_version 1 and a sections array';
    END IF;
    IF p_draft_version IS NULL OR btrim(p_draft_version) !~ '^[0-9]+\.[0-9]+\.[0-9]+$' THEN
       RAISE EXCEPTION 'Draft version must be numeric semver (for example 1.0.0)';
    END IF;
    IF nullif(btrim(p_tool_name),'') IS NULL THEN RAISE EXCEPTION 'Tool name is required'; END IF;
    IF EXISTS (SELECT 1 FROM public.cra_tm_tool_releases WHERE tool_id=p_tool_id AND release_version=btrim(p_draft_version)) THEN
       RAISE EXCEPTION 'Version % already released. Start a new version instead.',p_draft_version;
    END IF;
    UPDATE public.cra_tm_tool_drafts d
       SET definition=p_definition, draft_version=btrim(p_draft_version),
           revision=d.revision+1, updated_at=now()
     WHERE d.tool_id=p_tool_id AND d.revision=p_expected_revision AND d.is_locked=false
     RETURNING d.id,d.revision,d.updated_at INTO v_id,v_revision,v_updated;
    IF NOT FOUND THEN RAISE EXCEPTION 'Draft changed elsewhere, is locked, or was not found. Refresh before saving.'; END IF;
    UPDATE public.cra_tm_tools
       SET tool_name=btrim(p_tool_name),description=nullif(btrim(p_description),''),updated_at=now()
     WHERE id=p_tool_id AND tool_type='QUESTIONNAIRE';
    IF NOT FOUND THEN RAISE EXCEPTION 'Questionnaire tool not found'; END IF;
    RETURN QUERY SELECT v_id,v_revision,v_updated;
END; $body$;

CREATE OR REPLACE FUNCTION public.cra_tm_release_catalogue_tool(
    p_tool_id bigint, p_expected_revision bigint, p_release_notes text DEFAULT NULL
) RETURNS TABLE (release_id bigint, release_version text)
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO '' AS $body$
DECLARE
 d public.cra_tm_tool_drafts%ROWTYPE;
 t public.cra_tm_tools%ROWTYPE;
 s jsonb; q jsonb; o jsonb;
 v_section_codes text[]; v_question_codes text[]; v_option_codes text[];
 v_enabled integer := 0; v_active_options integer; v_default_options integer;
 v_supports_options boolean; v_qtype text; v_release_id bigint;
BEGIN
 SELECT * INTO d FROM public.cra_tm_tool_drafts WHERE tool_id=p_tool_id FOR UPDATE;
 IF NOT FOUND OR d.is_locked THEN RAISE EXCEPTION 'No editable draft exists for this tool'; END IF;
 IF d.revision IS DISTINCT FROM p_expected_revision THEN RAISE EXCEPTION 'Draft revision changed; refresh before release'; END IF;
 SELECT * INTO t FROM public.cra_tm_tools WHERE id=p_tool_id FOR UPDATE;
 IF NOT FOUND OR t.tool_type <> 'QUESTIONNAIRE' THEN RAISE EXCEPTION 'Only QUESTIONNAIRE releases are supported'; END IF;
 IF t.is_active=false THEN RAISE EXCEPTION 'Reactivate the tool before releasing'; END IF;
 IF jsonb_typeof(d.definition->'sections') <> 'array' OR jsonb_array_length(d.definition->'sections')=0 THEN
    RAISE EXCEPTION 'Add at least one section'; END IF;
 FOR s IN SELECT value FROM jsonb_array_elements(d.definition->'sections')
 LOOP
    IF jsonb_typeof(s)<>'object' OR nullif(btrim(s->>'section_name'),'') IS NULL THEN RAISE EXCEPTION 'Every section needs a name'; END IF;
    IF jsonb_typeof(s->'questions') <> 'array' THEN RAISE EXCEPTION 'Each section must have a questions array'; END IF;
    v_question_codes:=ARRAY[]::text[];
    FOR q IN SELECT value FROM jsonb_array_elements(s->'questions')
    LOOP
      IF jsonb_typeof(q)<>'object' OR nullif(btrim(q->>'question_text'),'') IS NULL THEN
         RAISE EXCEPTION 'Every question needs text'; END IF;
      IF nullif(btrim(q->>'question_code'),'') IS NULL THEN RAISE EXCEPTION 'Every question needs a code'; END IF;
      IF (q->>'question_code')=ANY(v_question_codes) THEN RAISE EXCEPTION 'Duplicate question code in section: %',q->>'question_code'; END IF;
      v_question_codes:=array_append(v_question_codes,q->>'question_code');
      v_qtype:=q->>'question_type';
      SELECT supports_options INTO v_supports_options FROM public.cra_tm_question_types
         WHERE type_code=v_qtype AND is_active=true;
      IF NOT FOUND THEN RAISE EXCEPTION 'Question type % is not active/known',v_qtype; END IF;
      IF jsonb_typeof(q->'options') <> 'array' THEN RAISE EXCEPTION 'Question % requires an options array',q->>'question_code'; END IF;
      v_option_codes:=ARRAY[]::text[]; v_active_options:=0; v_default_options:=0;
      FOR o IN SELECT value FROM jsonb_array_elements(q->'options')
      LOOP
          IF jsonb_typeof(o)<>'object' OR nullif(btrim(o->>'option_label'),'') IS NULL OR
             nullif(btrim(o->>'option_value'),'') IS NULL THEN RAISE EXCEPTION 'Option values and labels are required'; END IF;
          IF o->>'option_value'=ANY(v_option_codes) THEN RAISE EXCEPTION 'Duplicate option value for %',q->>'question_code'; END IF;
          v_option_codes:=array_append(v_option_codes,o->>'option_value');
          IF coalesce((o->>'is_enabled')::boolean,true) THEN v_active_options:=v_active_options+1; END IF;
          IF coalesce((o->>'is_default')::boolean,false) THEN v_default_options:=v_default_options+1; END IF;
      END LOOP;
      IF v_supports_options AND v_active_options<2 THEN
         RAISE EXCEPTION 'Question % needs two enabled answer options',q->>'question_code'; END IF;
      IF NOT v_supports_options AND jsonb_array_length(q->'options')>0 THEN
         RAISE EXCEPTION 'Non-option question % cannot include answer options',q->>'question_code'; END IF;
      IF coalesce((q->>'is_enabled')::boolean,true) AND coalesce((s->>'is_enabled')::boolean,true) THEN v_enabled:=v_enabled+1; END IF;
    END LOOP;
 END LOOP;
 IF v_enabled<1 THEN RAISE EXCEPTION 'At least one enabled question is required'; END IF;
 INSERT INTO public.cra_tm_tool_releases(tool_id,release_version,release_notes,definition,is_active)
 VALUES(p_tool_id,d.draft_version,nullif(btrim(p_release_notes),''),d.definition,true)
 RETURNING id INTO v_release_id;
 UPDATE public.cra_tm_tool_drafts SET is_locked=true,revision=revision+1,updated_at=now() WHERE id=d.id;
 RETURN QUERY SELECT v_release_id,d.draft_version;
END; $body$;

CREATE OR REPLACE FUNCTION public.cra_tm_start_catalogue_tool_version(
 p_tool_id bigint, p_next_version text
) RETURNS TABLE (draft_id bigint, revision bigint)
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO '' AS $body$
DECLARE d public.cra_tm_tool_drafts%ROWTYPE; v_definition jsonb; v_id bigint; v_revision bigint;
BEGIN
 IF p_next_version IS NULL OR btrim(p_next_version) !~ '^[0-9]+\.[0-9]+\.[0-9]+$' THEN
    RAISE EXCEPTION 'Next version must be numeric semver'; END IF;
 PERFORM 1 FROM public.cra_tm_tools WHERE id=p_tool_id AND tool_type='QUESTIONNAIRE' FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Questionnaire tool not found'; END IF;
 IF EXISTS(SELECT 1 FROM public.cra_tm_tool_releases WHERE tool_id=p_tool_id AND release_version=btrim(p_next_version)) THEN
    RAISE EXCEPTION 'Version already exists'; END IF;
 SELECT * INTO d FROM public.cra_tm_tool_drafts WHERE tool_id=p_tool_id FOR UPDATE;
 IF FOUND AND NOT d.is_locked THEN RAISE EXCEPTION 'Finish the current draft before starting a new version'; END IF;
 IF FOUND THEN
   UPDATE public.cra_tm_tool_drafts AS dr SET draft_version=btrim(p_next_version),is_locked=false,
       revision=dr.revision+1,updated_at=now() WHERE dr.id=d.id RETURNING dr.id,dr.revision INTO v_id,v_revision;
 ELSE
   SELECT definition INTO v_definition FROM public.cra_tm_tool_releases WHERE tool_id=p_tool_id
     ORDER BY created_at DESC,id DESC LIMIT 1;
   IF v_definition IS NULL OR v_definition->>'schema_version'<>'1' THEN
      RAISE EXCEPTION 'Existing tool releases have no compatible questionnaire definition'; END IF;
   INSERT INTO public.cra_tm_tool_drafts AS dr(tool_id,draft_version,definition)
     VALUES(p_tool_id,btrim(p_next_version),v_definition) RETURNING dr.id,dr.revision INTO v_id,v_revision;
 END IF;
 RETURN QUERY SELECT v_id,v_revision;
END; $body$;

CREATE OR REPLACE FUNCTION public.cra_tm_set_catalogue_release_active(
 p_release_id bigint,p_is_active boolean
) RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path TO '' AS $body$
BEGIN
 UPDATE public.cra_tm_tool_releases SET is_active=p_is_active,updated_at=now() WHERE id=p_release_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Tool release not found'; END IF;
END; $body$;

CREATE OR REPLACE FUNCTION public.cra_tm_set_catalogue_tool_active(
 p_tool_id bigint,p_is_active boolean
) RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path TO '' AS $body$
BEGIN
 UPDATE public.cra_tm_tools SET is_active=p_is_active,updated_at=now() WHERE id=p_tool_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Tool not found'; END IF;
END; $body$;

-- Materialize a released questionnaire into template-instance sections/questions/options.
-- Keeps existing Template Builder's cra_tm_save_tool_instance contract unchanged.
-- Only applies to newly attached schema_version=1 questionnaires.
CREATE OR REPLACE FUNCTION public.cra_tm_materialize_tool_release_on_attach()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path TO '' AS $body$
DECLARE v_def jsonb; v_type text; s jsonb; q jsonb; o jsonb;
        v_sid bigint; v_qid bigint;
BEGIN
    SELECT r.definition,t.tool_type INTO v_def,v_type
      FROM public.cra_tm_tool_releases r JOIN public.cra_tm_tools t ON t.id=r.tool_id
      WHERE r.id=NEW.tool_release_id;
    IF v_type<>'QUESTIONNAIRE' OR v_def->>'schema_version'<>'1'
       OR jsonb_typeof(v_def->'sections')<>'array' THEN
       RETURN NEW;
    END IF;
    -- Prevent duplicate population if an extension already seeded the instance.
    IF EXISTS(SELECT 1 FROM public.cra_tm_tool_sections WHERE tool_instance_id=NEW.id) THEN RETURN NEW; END IF;
    FOR s IN SELECT value FROM jsonb_array_elements(v_def->'sections')
    LOOP
      INSERT INTO public.cra_tm_tool_sections(tool_instance_id,section_name,description,display_order,is_enabled,configuration)
      VALUES(NEW.id,s->>'section_name',nullif(s->>'description',''),
        coalesce((s->>'display_order')::integer,0),coalesce((s->>'is_enabled')::boolean,true),
        coalesce(s->'configuration','{}'::jsonb)) RETURNING id INTO v_sid;
      FOR q IN SELECT value FROM jsonb_array_elements(s->'questions')
      LOOP
        INSERT INTO public.cra_tm_tool_questions(tool_section_id,question_code,question_text,friendly_name,
          description,question_hint,question_type,display_order,is_required,allows_attachment,allows_comment,
          configuration,validation_rules,is_enabled)
        VALUES(v_sid,q->>'question_code',q->>'question_text',nullif(q->>'friendly_name',''),
          nullif(q->>'description',''),nullif(q->>'question_hint',''),q->>'question_type',
          coalesce((q->>'display_order')::integer,0),coalesce((q->>'is_required')::boolean,true),
          coalesce((q->>'allows_attachment')::boolean,false),coalesce((q->>'allows_comment')::boolean,true),
          coalesce(q->'configuration','{}'::jsonb),coalesce(q->'validation_rules','{}'::jsonb),
          coalesce((q->>'is_enabled')::boolean,true)) RETURNING id INTO v_qid;
        FOR o IN SELECT value FROM jsonb_array_elements(q->'options')
        LOOP
          INSERT INTO public.cra_tm_tool_answer_options(question_id,option_value,option_label,option_hint,
              display_order,is_default,is_enabled,configuration)
          VALUES(v_qid,o->>'option_value',o->>'option_label',nullif(o->>'option_hint',''),
            coalesce((o->>'display_order')::integer,0),coalesce((o->>'is_default')::boolean,false),
            coalesce((o->>'is_enabled')::boolean,true),coalesce(o->'configuration','{}'::jsonb));
        END LOOP;
      END LOOP;
    END LOOP;
    RETURN NEW;
END; $body$;

-- New RPCs are not executable by PUBLIC by default; grant only to intended roles.
REVOKE ALL ON FUNCTION public.cra_tm_create_catalogue_tool(text,text,text) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.cra_tm_save_catalogue_tool_draft(bigint,bigint,jsonb,text,text,text) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.cra_tm_release_catalogue_tool(bigint,bigint,text) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.cra_tm_start_catalogue_tool_version(bigint,text) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.cra_tm_set_catalogue_release_active(bigint,boolean) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.cra_tm_set_catalogue_tool_active(bigint,boolean) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.cra_tm_materialize_tool_release_on_attach() FROM PUBLIC;

DROP TRIGGER IF EXISTS trg_cra_tm_materialize_tool_release_on_attach ON public.cra_tm_tool_instances;
CREATE TRIGGER trg_cra_tm_materialize_tool_release_on_attach
AFTER INSERT ON public.cra_tm_tool_instances
FOR EACH ROW EXECUTE FUNCTION public.cra_tm_materialize_tool_release_on_attach();

COMMIT;
